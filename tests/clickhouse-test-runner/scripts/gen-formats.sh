#!/usr/bin/env bash
# Generates formats.go from system.formats of a running ClickHouse server of
# the pinned version. The shim reads `FORMAT <word>` as the output-format
# clause only when <word> is one of these names; otherwise `format` is an
# identifier (a column, an alias or a table named `format`).
#
# Usage: scripts/gen-formats.sh
#
# Run it when you bump clickhouse-version, against a server of the new
# version. The server is at ${CLICKHOUSE_HOST:-localhost}:${CLICKHOUSE_PORT_HTTP:-8123}.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RUNNER_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
server_host="${CLICKHOUSE_HOST:-localhost}"
server_url="http"'://'"${server_host}:${CLICKHOUSE_PORT_HTTP:-8123}/"

version="$(curl -fsS --data-binary 'SELECT version()' "${server_url}")"
pinned="$("${SCRIPT_DIR}/pinned-version.sh")"
if [[ "${version}" != "${pinned}" ]]; then
  echo "Error: the server is ${version}, but clickhouse-version is ${pinned}. Start the pinned server." >&2
  exit 1
fi
names="$(curl -fsS --data-binary 'SELECT name FROM system.formats ORDER BY name FORMAT TSV' "${server_url}")"

out="${RUNNER_DIR}/formats.go"
{
  echo "// Code generated by scripts/gen-formats.sh from system.formats of ClickHouse ${version}; DO NOT EDIT."
  echo
  echo "package main"
  echo
  echo "// formatNames are the input and output formats of the server, in lower"
  echo "// case: format names are case-insensitive."
  echo "var formatNames = map[string]bool{"
  printf '%s\n' "${names}" | tr '[:upper:]' '[:lower:]' | sort -u | sed 's/.*/\t"&": true,/'
  echo "}"
} > "${out}"
gofmt -w "${out}"
echo "Wrote $(grep -cE ':[[:space:]]+true' "${out}") format names from ClickHouse ${version} to ${out}" >&2
