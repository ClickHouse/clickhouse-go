#!/usr/bin/env bash
# Generates errorcodes.go from src/Common/ErrorCodes.cpp of a ClickHouse
# checkout. fetch-upstream.sh runs it after each checkout, so the error names
# of the test hints always match the tests.
#
# Usage: scripts/gen-error-codes.sh [<ClickHouse checkout>]
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RUNNER_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
checkout="${1:-${UPSTREAM_CLICKHOUSE_DIR:-${RUNNER_DIR}/.upstream/ClickHouse}}"
src_file="${checkout}/src/Common/ErrorCodes.cpp"

if [[ ! -f "${src_file}" ]]; then
  echo "Error: ${src_file} not found. Run scripts/fetch-upstream.sh first." >&2
  exit 1
fi
ref="$(cat "${checkout}/.upstream-ref" 2>/dev/null || git -C "${checkout}" rev-parse HEAD)"

out="${RUNNER_DIR}/errorcodes.go"
{
  echo "// Code generated by scripts/gen-error-codes.sh from ClickHouse ${ref}; DO NOT EDIT."
  echo
  echo "package main"
  echo
  echo "// errorCodes maps the error names of ClickHouse's src/Common/ErrorCodes.cpp"
  echo "// to their codes. Test hints can name an error instead of giving its code."
  echo "var errorCodes = map[string]int32{"
  sed -n 's/^ *M(\([0-9][0-9]*\), *\([A-Z0-9_][A-Z0-9_]*\)).*/\t"\2": \1,/p' "${src_file}"
  echo "}"
  echo
  echo "var errorNames = func() map[int32]string {"
  echo "	m := make(map[int32]string, len(errorCodes))"
  echo "	for name, code := range errorCodes {"
  echo "		m[code] = name"
  echo "	}"
  echo "	return m"
  echo "}()"
} > "${out}"
gofmt -w "${out}"
echo "Wrote $(grep -c '^	"' "${out}") error codes from ${ref} to ${out}" >&2
